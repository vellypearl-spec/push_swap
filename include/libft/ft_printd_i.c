#include "libft.h"

int	ft_printd_i(int d)
{
	unsigned int	i;
	int				n;

	i = 1;
	n = d;
	if (d < 0 && n != -2147483648)
	{
		n = -d;
		i++;
	}
	while (n > 9)
	{
		n = n / 10;
		i++;
	}
	ft_putnbr_fd(d, 1);
	if (d == -2147483648)
		return (11);
	return (i);
}
